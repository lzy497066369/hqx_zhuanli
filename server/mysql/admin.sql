CREATE TABLE IF NOT EXISTS ai_request_logs (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  workspace_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  route VARCHAR(255) NOT NULL,
  model VARCHAR(255) NOT NULL,
  provider VARCHAR(512) NOT NULL,
  started_at TIMESTAMP(3) NOT NULL,
  finished_at TIMESTAMP(3) NULL,
  status VARCHAR(32) CHARACTER SET ascii NOT NULL,
  streaming BOOLEAN NOT NULL,
  http_status INT NULL,
  duration_ms INT UNSIGNED NULL,
  first_token_ms INT UNSIGNED NULL,
  input_tokens BIGINT UNSIGNED NULL,
  output_tokens BIGINT UNSIGNED NULL,
  total_tokens BIGINT UNSIGNED NULL,
  details JSON NOT NULL,
  INDEX idx_ai_logs_time (started_at, id),
  INDEX idx_ai_logs_user (user_id, started_at),
  INDEX idx_ai_logs_status (status, started_at),
  INDEX idx_ai_logs_request (request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
